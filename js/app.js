async function loadQuizData() {
  try {
    const resp = await fetch('data/dialects.json');
    if (resp.ok) {
      const json = await resp.json();
      if (json.quizQuestions && json.quizQuestions.length > 0) {
        dialectData.quizQuestions = json.quizQuestions;
      }
    }
  } catch (e) {
    console.warn('Could not load quiz data from dialects.json:', e);
  }
}

// ===== Navigation =====
function initNavigation() {
  const navBtns = document.querySelectorAll('.nav-btn');
  navBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      navBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      document.querySelectorAll('.section').forEach(s => s.classList.remove('active'));
      document.getElementById(btn.dataset.section).classList.add('active');
    });
  });
}

// ===== Categories =====
function populateCategories() {
  const select = document.getElementById('categoryFilter');
  dialectData.categories.forEach((cat, index) => {
    const option = document.createElement('option');
    option.value = index;
    option.textContent = cat.name;
    select.appendChild(option);
  });
  select.addEventListener('change', () => {
    renderComparison();
  });
}

// ===== Comparison Table =====
function renderComparison() {
  const tbody = document.getElementById('comparisonBody');
  const filter = document.getElementById('categoryFilter').value;

  let allWords = [];
  if (filter === 'all') {
    dialectData.categories.forEach(cat => {
      allWords = allWords.concat(cat.words);
    });
  } else {
    allWords = dialectData.categories[parseInt(filter)].words;
  }

  tbody.innerHTML = allWords.map(word => `
    <tr>
      <td>${word.english}</td>
      <td>${word.marathi}</td>
      <td>${word.varhadi}</td>
      <td>${word.ahirani}</td>
      <td>${word.vidarbhi}</td>
    </tr>
  `).join('');

  updateStats(allWords);
}

function updateStats(words) {
  document.getElementById('totalWords').textContent = words.length;
  let sameCount = 0;
  words.forEach(w => {
    if (w.marathi === w.varhadi && w.marathi === w.ahirani && w.marathi === w.vidarbhi) {
      sameCount++;
    }
  });
  document.getElementById('sameWords').textContent = sameCount;
  document.getElementById('diffWords').textContent = words.length - sameCount;
}

// ===== Poems =====
function buildPoemTabs() {
  const tabsContainer = document.getElementById('poemTabs');
  tabsContainer.innerHTML = '';
  dialectData.poems.forEach((poem, i) => {
    const btn = document.createElement('button');
    btn.className = 'poem-tab' + (i === 0 ? ' active' : '');
    btn.dataset.poem = i;
    btn.textContent = poem.title;
    tabsContainer.appendChild(btn);
  });
}

