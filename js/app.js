// ===== Quiz =====
let currentQuizIndex = 0;
let quizScore = 0;
let quizAnswered = false;

function initQuiz() {
  renderQuizQuestion();
  document.getElementById('restartBtn').addEventListener('click', () => {
    currentQuizIndex = 0;
    quizScore = 0;
    document.getElementById('quizResult').classList.add('hidden');
    document.getElementById('quizContainer').style.display = 'block';
    renderQuizQuestion();
  });
}

function renderQuizQuestion() {
  const questions = dialectData.quizQuestions;
  if (currentQuizIndex >= questions.length) {
    showQuizResult();
    return;
  }

  const q = questions[currentQuizIndex];
  quizAnswered = false;

  document.getElementById('quizProgress').textContent = `प्रश्न ${currentQuizIndex + 1} / ${questions.length}`;
  document.getElementById('progressFill').style.width = `${((currentQuizIndex) / questions.length) * 100}%`;
  document.getElementById('quizQuestion').textContent = q.question;

  const optionsContainer = document.getElementById('quizOptions');
  optionsContainer.innerHTML = q.options.map((opt, i) => `
    <button class="quiz-option" data-index="${i}">${opt}</button>
  `).join('');

  optionsContainer.querySelectorAll('.quiz-option').forEach(btn => {
    btn.addEventListener('click', () => handleAnswer(btn, q.correct));
  });

  document.getElementById('nextBtn').disabled = true;
  document.getElementById('nextBtn').textContent = currentQuizIndex === questions.length - 1 ? 'निकाल पहा' : 'पुढचा प्रश्न';
  document.getElementById('nextBtn').onclick = () => {
    currentQuizIndex++;
    renderQuizQuestion();
  };
}

function handleAnswer(btn, correctIndex) {
  if (quizAnswered) return;
  quizAnswered = true;

  const selectedIndex = parseInt(btn.dataset.index);
  const options = document.querySelectorAll('.quiz-option');

  options.forEach(opt => {
    opt.style.pointerEvents = 'none';
    if (parseInt(opt.dataset.index) === correctIndex) {
      opt.classList.add('correct');
    }
  });

  if (selectedIndex === correctIndex) {
    quizScore++;
    btn.classList.add('correct');
  } else {
    btn.classList.add('wrong');
  }

  document.getElementById('nextBtn').disabled = false;
}

function showQuizResult() {
  document.getElementById('quizContainer').style.display = 'none';
  document.getElementById('quizResult').classList.remove('hidden');

  const total = dialectData.quizQuestions.length;
  document.getElementById('scoreText').textContent = `${quizScore}/${total}`;

  const percentage = (quizScore / total) * 100;
  let message = '';
  if (percentage >= 80) message = 'अत्युत्तम! तुम्हाला बोलीभाषेची चांगली माहिती आहे!';
  else if (percentage >= 60) message = 'चांगले! थोड्या अभ्यासाची गरज आहे.';
  else if (percentage >= 40) message = 'ठीक आहे. अधिक अभ्यास करा.';
  else message = 'प्रयत्न करा. तुलनात्मक तक्ता पहा आणि पुन्हा प्रयत्न करा.';

  document.getElementById('scoreMessage').textContent = message;
}

