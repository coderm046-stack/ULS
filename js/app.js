// ===== Navigation =====
function initNavigation() {
  const navBtns = document.querySelectorAll('.nav-btn');
  navBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      navBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      document.querySelectorAll('.section').forEach(s => s.classList.remove('active'));
      document.getElementById(btn.dataset.section).classList.add('active');
    });
  });
}

// ===== Categories =====
function populateCategories() {
  const select = document.getElementById('categoryFilter');
  dialectData.categories.forEach((cat, index) => {
    const option = document.createElement('option');
    option.value = index;
    option.textContent = cat.name;
    select.appendChild(option);
  });
  select.addEventListener('change', () => {
    renderComparison();
  });
}

// ===== Comparison Table =====
function renderComparison() {
  const tbody = document.getElementById('comparisonBody');
  const filter = document.getElementById('categoryFilter').value;

  let allWords = [];
  if (filter === 'all') {
    dialectData.categories.forEach(cat => {
      allWords = allWords.concat(cat.words);
    });
  } else {
    allWords = dialectData.categories[parseInt(filter)].words;
  }

  tbody.innerHTML = allWords.map(word => `
    <tr>
      <td>${word.english}</td>
      <td>${word.marathi}</td>
      <td>${word.varhadi}</td>
      <td>${word.ahirani}</td>
      <td>${word.vidarbhi}</td>
    </tr>
  `).join('');

  updateStats(allWords);
}

function updateStats(words) {
  document.getElementById('totalWords').textContent = words.length;
  let sameCount = 0;
  words.forEach(w => {
    if (w.marathi === w.varhadi && w.marathi === w.ahirani && w.marathi === w.vidarbhi) {
      sameCount++;
    }
  });
  document.getElementById('sameWords').textContent = sameCount;
  document.getElementById('diffWords').textContent = words.length - sameCount;
}

// ===== Poems =====
function buildPoemTabs() {
  const tabsContainer = document.getElementById('poemTabs');
  tabsContainer.innerHTML = '';
  dialectData.poems.forEach((poem, i) => {
    const btn = document.createElement('button');
    btn.className = 'poem-tab' + (i === 0 ? ' active' : '');
    btn.dataset.poem = i;
    btn.textContent = poem.title;
    tabsContainer.appendChild(btn);
  });
}

function renderPoem(index) {
  const poem = dialectData.poems[index];
  const container = document.getElementById('poemContainer');

  container.innerHTML = `
    <h3 class="poem-title">${poem.title}</h3>
    <p class="poem-meta">कवी: ${poem.poet} | बोली: ${poem.dialect}</p>
    <div class="poem-lines">
      ${poem.lines.map(line => `<p>${line}</p>`).join('')}
    </div>
    <div class="poem-meaning">
      <h4>अर्थ:</h4>
      <p>${poem.meaning}</p>
    </div>
  `;

  document.querySelectorAll('.poem-tab').forEach(tab => {
    tab.onclick = () => {
      document.querySelectorAll('.poem-tab').forEach(t => t.classList.remove('active'));
      tab.classList.add('active');
      renderPoem(parseInt(tab.dataset.poem));
    };
  });
}

// ===== Quiz =====
let currentQuizIndex = 0;
let quizScore = 0;
let quizAnswered = false;

function initQuiz() {
  renderQuizQuestion();
  document.getElementById('restartBtn').addEventListener('click', () => {
    currentQuizIndex = 0;
    quizScore = 0;
    document.getElementById('quizResult').classList.add('hidden');
    document.getElementById('quizContainer').style.display = 'block';
    renderQuizQuestion();
  });
}

function renderQuizQuestion() {
  const questions = dialectData.quizQuestions;
  if (currentQuizIndex >= questions.length) {
    showQuizResult();
    return;
  }

  const q = questions[currentQuizIndex];
  quizAnswered = false;

  document.getElementById('quizProgress').textContent = `प्रश्न ${currentQuizIndex + 1} / ${questions.length}`;
  document.getElementById('progressFill').style.width = `${((currentQuizIndex) / questions.length) * 100}%`;
  document.getElementById('quizQuestion').textContent = q.question;

  const optionsContainer = document.getElementById('quizOptions');
  optionsContainer.innerHTML = q.options.map((opt, i) => `
    <button class="quiz-option" data-index="${i}">${opt}</button>
  `).join('');

  optionsContainer.querySelectorAll('.quiz-option').forEach(btn => {
    btn.addEventListener('click', () => handleAnswer(btn, q.correct));
  });

  document.getElementById('nextBtn').disabled = true;
  document.getElementById('nextBtn').textContent = currentQuizIndex === questions.length - 1 ? 'निकाल पहा' : 'पुढचा प्रश्न';
  document.getElementById('nextBtn').onclick = () => {
    currentQuizIndex++;
    renderQuizQuestion();
  };
}

function handleAnswer(btn, correctIndex) {
  if (quizAnswered) return;
  quizAnswered = true;

  const selectedIndex = parseInt(btn.dataset.index);
  const options = document.querySelectorAll('.quiz-option');

  options.forEach(opt => {
    opt.style.pointerEvents = 'none';
    if (parseInt(opt.dataset.index) === correctIndex) {
      opt.classList.add('correct');
    }
  });

  if (selectedIndex === correctIndex) {
    quizScore++;
    btn.classList.add('correct');
  } else {
    btn.classList.add('wrong');
  }

  document.getElementById('nextBtn').disabled = false;
}

function showQuizResult() {
  document.getElementById('quizContainer').style.display = 'none';
  document.getElementById('quizResult').classList.remove('hidden');

  const total = dialectData.quizQuestions.length;
  document.getElementById('scoreText').textContent = `${quizScore}/${total}`;

  const percentage = (quizScore / total) * 100;
  let message = '';
  if (percentage >= 80) message = 'अत्युत्तम! तुम्हाला बोलीभाषेची चांगली माहिती आहे!';
  else if (percentage >= 60) message = 'चांगले! थोड्या अभ्यासाची गरज आहे.';
  else if (percentage >= 40) message = 'ठीक आहे. अधिक अभ्यास करा.';
  else message = 'प्रयत्न करा. तुलनात्मक तक्ता पहा आणि पुन्हा प्रयत्न करा.';

  document.getElementById('scoreMessage').textContent = message;
}

