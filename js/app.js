function initMap() {
  const svg = document.getElementById('maharashtraMap');
  const tooltip = document.getElementById('districtTooltip');
  const legend = document.getElementById('mapLegend');

  if (!svg || !tooltip || !legend) return;

  const ns = 'http://www.w3.org/2000/svg';
  const dotsGroup = document.createElementNS(ns, 'g');
  dotsGroup.setAttribute('id', 'districtDots');
  svg.appendChild(dotsGroup);

  districtDialectData.forEach(d => {
    const circle = document.createElementNS(ns, 'circle');
    circle.setAttribute('cx', d.x);
    circle.setAttribute('cy', d.y);
    circle.setAttribute('r', '4.5');
    circle.setAttribute('fill', regionColors[d.region] || '#1d3557');
    circle.setAttribute('class', 'district-dot');
    circle.setAttribute('data-name', d.name);
    circle.setAttribute('data-region', d.region);
    circle.setAttribute('data-dialects', d.dialects);

    circle.addEventListener('mouseenter', (e) => {
      tooltip.innerHTML = `
        <div class="tt-district">${d.name}</div>
        <div class="tt-region">${d.region}</div>
        <div class="tt-dialects">बोलीभाषा: ${d.dialects}</div>
      `;
      tooltip.style.display = 'block';

      const mapContainer = svg.closest('.map-container');
      const rect = mapContainer.getBoundingClientRect();
      const svgRect = svg.getBoundingClientRect();
      const scaleX = 500 / svgRect.width;
      const scaleY = 420 / svgRect.height;
      const tooltipX = (d.x / scaleX) + svgRect.left - rect.left + 10;
      const tooltipY = (d.y / scaleY) + svgRect.top - rect.top - 60;
      tooltip.style.left = tooltipX + 'px';
      tooltip.style.top = tooltipY + 'px';
    });

    circle.addEventListener('mouseleave', () => {
      tooltip.style.display = 'none';
    });

    circle.addEventListener('click', () => {
      document.querySelectorAll('.district-dot').forEach(c => c.classList.remove('active'));
      circle.classList.add('active');

      legend.innerHTML = `
        <div class="map-info-card">
          <h3>${d.name}</h3>
          <div class="dialect-info">
            <div class="dialect-name">विभाग:</div>
            <div class="dialect-region">${d.region}</div>
          </div>
          <div class="dialect-info">
            <div class="dialect-name">प्रमुख बोलीभाषा:</div>
            <div class="dialect-region">${d.dialects}</div>
          </div>
        </div>
      `;
    });

    dotsGroup.appendChild(circle);
  });
}

// ===== QR Code =====
function initQR() {
  const base = window.location.origin + window.location.pathname.replace(/\/[^/]*$/, '/');
  const dialectUrls = {
    qrVarhadi: base + 'play-warli.html',
    qrAhirani: base + 'play-ahirani.html',
    qrVidarbhi: base + 'play-vaidarbhi.html',
    qrKokani: base + 'play-kokani.html'
  };

  Object.entries(dialectUrls).forEach(([id, url]) => {
    generateQR(id, url, 120);
  });

  const generateQrBtn = document.getElementById('generateQr');
  if (generateQrBtn) {
    generateQrBtn.addEventListener('click', () => {
      const url = document.getElementById('customUrl').value.trim();
      if (url) generateQR('customQr', url, 200);
    });
  }

  const generateStudentQrBtn = document.getElementById('generateStudentQr');
  if (generateStudentQrBtn) {
    generateStudentQrBtn.addEventListener('click', () => {
      const url = document.getElementById('studentAudioUrl').value.trim();
      if (url) generateQR('studentQr', url, 200);
    });
  }
}

function generateQR(elementId, url, size) {
  const container = document.getElementById(elementId);
  container.innerHTML = '';

  if (typeof QRCode !== 'undefined') {
    new QRCode(container, {
      text: url,
      width: size,
      height: size,
      colorDark: '#1d3557',
      colorLight: '#ffffff',
      correctLevel: QRCode.CorrectLevel.H
    });
  } else {
    container.innerHTML = `<div style="padding: 1rem; background: #f8f9fa; border-radius: 8px; word-break: break-all;"><p>URL: <a href="${url}" target="_blank">${url}</a></p></div>`;
  }
}

// ===== Boli Audio Playback =====
function toggleBoliAudio(dialect) {
  const audio = document.getElementById('audio-' + dialect);
  const btn = document.querySelector('[onclick*="' + dialect + '"]');
  if (!audio) return;

  // Pause all other audio first
  document.querySelectorAll('.boli-card audio').forEach(a => {
    if (a.id !== 'audio-' + dialect) {
      a.pause();
      a.currentTime = 0;
    }
  });
  document.querySelectorAll('.boli-audio-btn').forEach(b => {
    if (b !== btn) b.classList.remove('playing');
  });

  if (audio.paused) {
    audio.play();
    btn.classList.add('playing');
  } else {
    audio.pause();
    btn.classList.remove('playing');
  }
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.boli-card audio').forEach(audio => {
    audio.addEventListener('ended', () => {
      const dialect = audio.id.replace('audio-', '');
      const btn = document.querySelector('[onclick*="' + dialect + '"]');
      if (btn) btn.classList.remove('playing');
    });
  });

  // Poem audio ended handler
  const khopyaAudio = document.getElementById('audio-khopya');
  if (khopyaAudio) {
    khopyaAudio.addEventListener('ended', () => {
      const btn = document.querySelector('[onclick*="khopya"]');
      if (btn) btn.classList.remove('playing');
    });
  }
});

// ===== Poem Audio Playback =====
function togglePoemAudio(id) {
  const audio = document.getElementById('audio-' + id);
  const btn = document.querySelector('[onclick*="' + id + '"]');
  const status = document.getElementById(id + '-status');
  if (!audio) return;

  if (audio.paused) {
    audio.load();
    const playPromise = audio.play();
    if (playPromise !== undefined) {
      playPromise.then(() => {
        btn.classList.add('playing');
        if (status) status.textContent = '';
      }).catch(err => {
        if (status) status.textContent = 'Audio load error: ' + err.message;
      });
    }
  } else {
    audio.pause();
    btn.classList.remove('playing');
  }
}
